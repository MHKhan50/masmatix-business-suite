#!/usr/bin/env python3
"""Build CRUD modules for the business suite from small JSON spec files.

For every entity in specs/*.json this writes:
  backend  .../generated/<system>/<Entity>.java, <Entity>Repository.java, <Entity>Controller.java
  backend  src/main/resources/seed/<system>-<path>.json   (only if the spec has "samples")
  frontend src/generated/systems.json                       (menu + form definitions for every system)

Usage (from the repo root, Python 3.9+, standard library only):
  python3 tools/generator/generate.py           # write files
  python3 tools/generator/generate.py --check   # exit 1 if generated files are out of date
"""
from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path
from typing import Dict, List, Tuple

ROOT = Path(__file__).resolve().parents[2]
SPECS = ROOT / "specs"
JAVA_ROOT = ROOT / "backend/src/main/java/com/masmatix/suite/generated"
SEED_ROOT = ROOT / "backend/src/main/resources/seed"
FRONT_OUT = ROOT / "frontend/src/generated/systems.json"
BASE_PKG = "com.masmatix.suite.generated"

FIELD_TYPES = {"string", "text", "int", "decimal", "bool", "date", "email", "phone", "enum"}
JAVA_KEYWORDS = {"class", "default", "package", "public", "private", "new", "case", "enum", "int", "boolean"}
NAME_RE = re.compile(r"^[a-z][a-zA-Z0-9]*$")
ENTITY_RE = re.compile(r"^[A-Z][a-zA-Z0-9]*$")
SYSTEM_RE = re.compile(r"^[a-z][a-z0-9]*$")
PATH_RE = re.compile(r"^[a-z][a-z0-9-]*$")


class SpecError(ValueError):
    pass


def snake(name: str) -> str:
    return re.sub(r"(?<!^)(?=[A-Z])", "_", name).lower()


def header(spec_file: str) -> str:
    return "// Generated by tools/generator/generate.py from specs/%s. Do not edit by hand.\n" % spec_file


# ---------------------------------------------------------------- validation

def validate(spec: dict, fname: str) -> None:
    system = spec.get("system", "")
    if not SYSTEM_RE.match(system):
        raise SpecError("%s: 'system' must be lowercase letters/digits" % fname)
    if not spec.get("entities"):
        raise SpecError("%s: needs at least one entity" % fname)
    for ent in spec["entities"]:
        name = ent.get("name", "")
        if not ENTITY_RE.match(name):
            raise SpecError("%s: entity name '%s' must be PascalCase" % (fname, name))
        if not PATH_RE.match(ent.get("path", "")):
            raise SpecError("%s: %s.path must be lowercase-with-dashes" % (fname, name))
        seen = set()
        for f in ent.get("fields", []):
            fn, ft = f.get("name", ""), f.get("type", "")
            if not NAME_RE.match(fn) or fn in JAVA_KEYWORDS or fn in {"id", "createdAt", "updatedAt"}:
                raise SpecError("%s: %s field name '%s' is not allowed" % (fname, name, fn))
            if fn in seen:
                raise SpecError("%s: %s has duplicate field '%s'" % (fname, name, fn))
            seen.add(fn)
            if ft not in FIELD_TYPES:
                raise SpecError("%s: %s.%s has unknown type '%s'" % (fname, name, fn, ft))
            if f.get("unique") and ft not in {"string", "email", "phone"}:
                raise SpecError("%s: %s.%s 'unique' is only for string, email or phone" % (fname, name, fn))
            if ft == "enum" and not f.get("values"):
                raise SpecError("%s: %s.%s enum needs 'values'" % (fname, name, fn))
        if not seen:
            raise SpecError("%s: %s needs at least one field" % (fname, name))


# ---------------------------------------------------------------- java

def java_field(f: dict) -> Tuple[List[str], str]:
    t, name = f["type"], f["name"]
    ann: List[str] = []
    required = f.get("required", False)
    if t in {"string", "email", "phone", "enum", "text"}:
        jt = "String"
        length = {"text": 2000, "phone": 30, "email": 160, "enum": 40}.get(t, f.get("max", 120))
        if required:
            ann.append("@NotBlank")
        ann.append("@Size(max = %d)" % length)
        if t == "email":
            ann.append("@Email")
        if t == "phone":
            ann.append('@Pattern(regexp = "^[+0-9 ()-]{0,30}$", message = "must be a phone number")')
        if t == "enum":
            ann.append('@Pattern(regexp = "^(%s)?$", message = "must be one of %s")'
                       % ("|".join(f["values"]), ", ".join(f["values"])))
        ann.append("@Column(length = %d%s%s)" % (length, ", nullable = false" if required else "",
                                                 ", unique = true" if f.get("unique") else ""))
    elif t == "int":
        jt = "Integer"
        if required:
            ann.append("@NotNull")
        if "min" in f:
            ann.append("@Min(%d)" % int(f["min"]))
        if "max" in f:
            ann.append("@Max(%d)" % int(f["max"]))
    elif t == "decimal":
        jt = "BigDecimal"
        if required:
            ann.append("@NotNull")
        if "min" in f:
            ann.append('@DecimalMin("%s")' % f["min"])
        ann.append("@Column(precision = 12, scale = 2)")
    elif t == "bool":
        jt = "Boolean"
    else:  # date
        jt = "LocalDate"
        if required:
            ann.append("@NotNull")
    return ["    " + a for a in ann] + ["    private %s %s;" % (jt, name), ""], jt


def entity_java(system: str, ent: dict, spec_file: str) -> str:
    pkg = "%s.%s" % (BASE_PKG, system)
    body: List[str] = []
    accessors: List[str] = []
    for f in ent["fields"]:
        lines, jt = java_field(f)
        body.extend(lines)
        cap = f["name"][0].upper() + f["name"][1:]
        accessors.append("    public %s get%s() { return %s; }" % (jt, cap, f["name"]))
        accessors.append("    public void set%s(%s v) { this.%s = v; }" % (cap, jt, f["name"]))
    return (
        header(spec_file)
        + "package %s;\n\n" % pkg
        + "import com.masmatix.suite.core.crud.BaseEntity;\n"
        + "import jakarta.persistence.*;\n"
        + "import jakarta.validation.constraints.*;\n"
        + "import java.math.BigDecimal;\n"
        + "import java.time.LocalDate;\n\n"
        + "@Entity\n@Table(name = \"%s_%s\")\n" % (system, snake(ent["name"]))
        + "public class %s extends BaseEntity {\n\n" % ent["name"]
        + "\n".join(body) + "\n"
        + "\n".join(accessors) + "\n}\n"
    )


def repo_java(system: str, ent: dict, spec_file: str) -> str:
    return (
        header(spec_file)
        + "package %s.%s;\n\n" % (BASE_PKG, system)
        + "import org.springframework.data.jpa.repository.JpaRepository;\n\n"
        + "public interface %sRepository extends JpaRepository<%s, Long> {}\n" % (ent["name"], ent["name"])
    )


def controller_java(system: str, ent: dict, spec_file: str) -> str:
    n = ent["name"]
    return (
        header(spec_file)
        + "package %s.%s;\n\n" % (BASE_PKG, system)
        + "import com.masmatix.suite.core.audit.AuditService;\n"
        + "import com.masmatix.suite.core.crud.CrudController;\n"
        + "import org.springframework.web.bind.annotation.RequestMapping;\n"
        + "import org.springframework.web.bind.annotation.RestController;\n\n"
        + "@RestController\n@RequestMapping(\"/api/%s/%s\")\n" % (system, ent["path"])
        + "public class %sController extends CrudController<%s> {\n" % (n, n)
        + "    public %sController(%sRepository repository, AuditService audit) {\n" % (n, n)
        + "        super(repository, audit, \"%s\");\n" % snake(n)
        + "    }\n}\n"
    )


# ---------------------------------------------------------------- run

def build(specs_dir: Path) -> Dict[Path, str]:
    """Return {output path: content} for every file the specs produce."""
    out: Dict[Path, str] = {}
    systems = []
    for spec_path in sorted(specs_dir.glob("*.json")):
        spec = json.loads(spec_path.read_text(encoding="utf-8"))
        validate(spec, spec_path.name)
        system = spec["system"]
        front_entities = []
        for ent in spec["entities"]:
            d = JAVA_ROOT / system
            out[d / ("%s.java" % ent["name"])] = entity_java(system, ent, spec_path.name)
            out[d / ("%sRepository.java" % ent["name"])] = repo_java(system, ent, spec_path.name)
            out[d / ("%sController.java" % ent["name"])] = controller_java(system, ent, spec_path.name)
            if ent.get("samples"):
                seed = {"entity": "%s.%s.%s" % (BASE_PKG, system, ent["name"]),
                        "note": "Invented sample data for demos. Not real people or businesses.",
                        "rows": ent["samples"]}
                out[SEED_ROOT / ("%s-%s.json" % (system, ent["path"]))] = json.dumps(seed, indent=2) + "\n"
            front_entities.append({
                "name": ent["name"], "label": ent.get("label", ent["name"] + "s"),
                "path": ent["path"], "api": "/api/%s/%s" % (system, ent["path"]),
                "fields": [{k: v for k, v in f.items()} for f in ent["fields"]],
            })
        systems.append({"system": system, "title": spec.get("title", system),
                        "entities": front_entities})
    out[FRONT_OUT] = json.dumps(systems, indent=2) + "\n"
    return out


def main(argv: List[str]) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true", help="only report out-of-date files")
    args = ap.parse_args(argv)
    try:
        files = build(SPECS)
    except SpecError as e:
        print("Spec error: %s" % e, file=sys.stderr)
        return 2
    stale = [p for p, c in files.items() if not p.exists() or p.read_text(encoding="utf-8") != c]
    if args.check:
        for p in stale:
            print("out of date: %s" % p.relative_to(ROOT))
        return 1 if stale else 0
    for p in stale:
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(files[p], encoding="utf-8")
    print("%d files checked, %d written" % (len(files), len(stale)))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
